/**
 * Leitura e escrita seguras no `localStorage`. Em navegadores com armazenamento
 * bloqueado (`SecurityError`) ou cota cheia (`QuotaExceededError`), a operação
 * falha sem derrubar a interface — a preferência vale só para a visita atual.
 */
export function readStorageItem(key: string): string | null {
  if (typeof window === "undefined") {
    return null;
  }

  try {
    return window.localStorage.getItem(key);
  } catch {
    return null;
  }
}

export function writeStorageItem(key: string, value: string): boolean {
  if (typeof window === "undefined") {
    return false;
  }

  try {
    window.localStorage.setItem(key, value);
    return true;
  } catch {
    return false;
  }
}

export function removeStorageItem(key: string): boolean {
  if (typeof window === "undefined") {
    return false;
  }

  try {
    window.localStorage.removeItem(key);
    return true;
  } catch {
    return false;
  }
}
